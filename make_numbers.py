#!/usr/bin/env python3
"""Write LaTeX macros (numbers.tex) from results/summary.json so that every number quoted in
the manuscript text and in the response letter is taken from the result files."""
import json
import sys
from pathlib import Path

R = Path(sys.argv[1] if len(sys.argv) > 1 else "results")
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else "../manuscript/numbers.tex")
s = json.load(open(R / "summary.json"))
m = {}
b = s["breaks"]
m["NMonths"] = str(b["n_months"])
m["AnnYears"] = f"{b['ann_years'][0]}--{b['ann_years'][1]}"
m["TSslope"] = f"{10*b['theil_slope_per_yr']:+.4f}"
m["TSci"] = f"[{10*b['theil_lo']:+.4f}, {10*b['theil_hi']:+.4f}]"
m["KendallTau"] = f"{b['kendall_tau']:.2f}"
m["KendallP"] = f"{b['kendall_p']:.3f}"
m["GHIslope"] = f"{b['ghi_slope']:+.1f}"
m["KPSSstat"] = f"{b['kpss'][0]:.3f}"
m["KPSSp"] = f"{b['kpss'][1]:.3f}"

a = s.get("agg_lead1", {})
P, C, O = "Proposed (Bayesian-GAN-MC)", "Climatology", "Oracle covariates (diagnostic)"
def g(model, key, fmt="{:.0f}"):
    try:
        return fmt.format(a[model][key])
    except KeyError:
        return "--"
for tag, model in [("prop", P), ("clim", C), ("oracle", O), ("bsts", "BSTS"), ("dens", "Deep ensemble PatchTST"),
                   ("diff", "Conditional diffusion (CSDI-style)"), ("chronos", "Chronos-Bolt (zero-shot)"),
                   ("timesfm", "TimesFM 2.5 (zero-shot)"), ("Aone", "A1: bootstrap scenarios (no GAN)"),
                   ("Afive", "A5: no drift component"), ("prophet", "Prophet"), ("arima", "ARIMA(1,0,1)"),
                   ("mcd", "MC-dropout PatchTST"), ("ptst", "PatchTST (point)"), ("moment", "MOMENT (linear probe)"),
                   ("Atwo", "A2: deterministic GAN (no Bayesian prior)"), ("Athree", "A3: no Monte Carlo (single mean path)"),
                   ("Afour", "A4: linear-Gaussian (no PatchTST)"), ("snaive", "Seasonal naive")]:
    m[f"CRPS{tag}"] = g(model, "CRPS")
    m[f"MAE{tag}"] = g(model, "MAE")
    m[f"RMSE{tag}"] = g(model, "RMSE")
    m[f"PICP{tag}"] = g(model, "PICP", "{:.1f}")
    m[f"PINAW{tag}"] = g(model, "PINAW", "{:.3f}")
    m[f"CRPSS{tag}"] = g(model, "CRPSS", "{:+.1f}")
    m[f"mCRPS{tag}"] = g(model, "m_CRPS")
    m[f"mCRPSS{tag}"] = g(model, "m_CRPSS", "{:+.1f}")
so = s.get("sobol", {}).get("meta", {})
m["SobolN"] = f"{so.get('N', '--'):,}" if so else "--"
m["SobolD"] = str(so.get("d", "--"))
m["SobolEval"] = f"{so.get('n_eval', 0):,}" if so else "--"
m["SobolSumS"] = f"{so.get('sum_S1', float('nan')):.3f}" if so else "--"
import pandas as pd
if (R / "mc_sensitivity.csv").exists():
    mc = pd.read_csv(R / "mc_sensitivity.csv").groupby("S").mean()
    for S_ in (50, 200, 1000):
        word = {50: "fifty", 200: "twohundred", 1000: "thousand"}[S_]
        m[f"MCcrps{word}"] = f"{mc.loc[S_, 'CRPS']:.1f}"
        m[f"MCtime{word}"] = f"{mc.loc[S_, 'time_s']:.0f}"
        m[f"MCpicp{word}"] = f"{mc.loc[S_, 'PICP']:.1f}"
if (R / "sobol.csv").exists():
    sb = pd.read_csv(R / "sobol.csv").set_index("feature")
    for f_, nm in [("Ps", "Ps"), ("WDs", "U"), ("WS", "WS"), ("Prec", "Prec"), ("Temp", "Temp")]:
        if f_ in sb.index:
            m[f"SobolSone{nm}"] = f"{sb.loc[f_, 'S1']:.3f}"
            m[f"SobolST{nm}"] = f"{sb.loc[f_, 'ST']:.3f}"
    m["SobolOutSD"] = f"{s['sobol']['meta']['output_sd']:.0f}"
pr = s.get("projection")
if pr:
    rows = {r[0]: r for r in pr["rows"]}
    for y_ in (2025, 2045):
        if y_ in rows:
            m[f"Proj{'A' if y_ == 2025 else 'B'}med"] = rows[y_][1].replace(",", "{,}")
            m[f"Proj{'A' if y_ == 2025 else 'B'}rng"] = rows[y_][2].replace(",", "{,}")
    m["ProjObsMean"] = f"{pr['obs_mean']:,.0f}".replace(",", "{,}")
bn = s.get("bn1_selection", {})
m["NOrigins"] = str(bn.get("n", 8))
lines = ["% Auto-generated by code/make_numbers.py from results/summary.json -- do not edit by hand"]
for k, v in m.items():
    k2 = k.replace("1", "one").replace("5", "five")
    v = v.replace("-", "$-$", 1) if v.startswith("-") and v[1:2].isdigit() else v
    v = v.replace("[-", "[$-$").replace(", -", ", $-$")
    lines.append(f"\\newcommand{{\\{k2}}}{{{v}}}")
OUT.write_text("\n".join(lines) + "\n")
print(OUT.read_text())
